// Responsive image pipeline. Reads master photos from media-src/photos/ and
// emits web-ready WebP derivatives at a few widths into media/photos/, plus a
// manifest the client uses to build <img srcset>. Local dev only — run with
// `npm run images`. The deployed site stays static (CI only runs the route
// generator); the derivatives + manifest are committed, the masters are the
// source of truth.
//
// Masters today are stand-in placeholders living in the repo. Later, repoint
// SRC_DIR at a Drive/Dropbox sync folder and keep the real masters out of git.

import sharp from "sharp";
import { readdirSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join, basename, extname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC_DIR = join(root, "media-src", "photos");
const OUT_DIR = join(root, "media", "photos");

// Target widths span carousel thumbs up to a near-full-viewport focused cover.
// A master is never upscaled: we keep only targets <= its width, then add the
// master's own width as the sharpest step (capped at the largest target).
const TARGET_WIDTHS = [160, 320, 640, 1280];
const QUALITY = 80;

const files = readdirSync(SRC_DIR).filter((f) =>
  /\.(png|jpe?g|webp|tiff?)$/i.test(f)
);
if (files.length === 0) {
  console.error(`No master images found in ${SRC_DIR}`);
  process.exit(1);
}

// Rebuild the output dir from scratch so renamed/removed masters never leave
// orphaned derivatives behind.
rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

const manifest = {};

for (const file of files) {
  const base = basename(file, extname(file));
  const input = sharp(join(SRC_DIR, file));
  const meta = await input.metadata();
  const srcW = meta.width;
  const srcH = meta.height;

  let widths = TARGET_WIDTHS.filter((w) => w <= srcW);
  const maxTarget = TARGET_WIDTHS[TARGET_WIDTHS.length - 1];
  if (srcW < maxTarget && !widths.includes(srcW)) widths.push(srcW);
  if (widths.length === 0) widths = [srcW];

  for (const w of widths) {
    await input
      .clone()
      .resize({ width: w, withoutEnlargement: true })
      .webp({ quality: QUALITY })
      .toFile(join(OUT_DIR, `${base}-${w}.webp`));
  }

  // Intrinsic dimensions let the client set aspect-ratio and kill layout shift.
  manifest[base] = { w: srcW, h: srcH, widths };
  console.log(`  ${base}  ${srcW}×${srcH}  →  ${widths.join(", ")}`);
}

// Emitted as a tiny JS file (not JSON) so it loads synchronously via a <script>
// tag before script.js — the carousel renders on load and needs it available
// immediately, with no fetch race.
const banner =
  "/* Generated by scripts/build-images.mjs — do not edit by hand. */\n";
writeFileSync(
  join(OUT_DIR, "manifest.js"),
  `${banner}window.PHOTO_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`
);

console.log(
  `\nBuilt ${files.length} image(s) → ${OUT_DIR} and wrote manifest.js`
);
